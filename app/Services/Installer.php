<?php
namespace App\Services;

use App\Core\Auth;
use App\Core\DB;

/** Creates the tables and default data in the configured PostgreSQL database (Supabase). Used by /install and database/install.php. */
class Installer
{
    /** Sample catalogs that can be loaded on a new installation. */
    public const SAMPLES = ['none' => 'No sample data (empty catalog)', 'pharmacy' => 'Pharmacy / drugstore', 'grocery' => 'Grocery / sari-sari / minimart', 'hardware' => 'Hardware / construction supply'];

    /** Local development only: create the database on a self-hosted PostgreSQL server (Supabase already has one). */
    public static function createDatabase(string $name): void
    {
        if (!preg_match('/^\w+$/', $name)) throw new \InvalidArgumentException('Database name may only contain letters, numbers and _');
        $server = DB::server();
        if (!$server->query("SELECT 1 FROM pg_database WHERE datname = " . $server->quote($name))->fetchColumn()) {
            $server->exec("CREATE DATABASE \"$name\" ENCODING 'UTF8'");
        }
        DB::reconnect();
    }

    /** Create the schema (if it is not "public") and run every statement in database/schema.sql (all re-runnable). */
    public static function createTables(): void
    {
        $schema = DB::schema();
        if ($schema !== 'public') DB::pdo()->exec('CREATE SCHEMA IF NOT EXISTS ' . DB::quoteIdent($schema));
        DB::reconnect();
        foreach (self::statements(file_get_contents(BASE_PATH . '/database/schema.sql')) as $sql) {
            DB::pdo()->exec($sql);
        }
    }

    /** Split a .sql file into statements (statements end with ";" at the end of a line). */
    public static function statements(string $sql): array
    {
        $sql = preg_replace('/^\s*--.*$/m', '', $sql);
        $parts = preg_split('/;\s*(\r?\n|$)/', $sql);
        return array_values(array_filter(array_map('trim', $parts), fn ($s) => $s !== ''));
    }

    /**
     * Full installation: tables, default data, admin user and (optionally) a sample catalog.
     * $sample: none | pharmacy | grocery | hardware (true = pharmacy, false = none for backwards compatibility).
     */
    public static function install($sample = 'none', string $adminPassword = 'admin123', string $adminPin = '1234'): void
    {
        if ($sample === true) $sample = 'pharmacy';
        if ($sample === false || $sample === null || $sample === '') $sample = 'none';
        self::createTables();
        Seeder::base($adminPassword, $adminPin);
        Migrations::run();   // marks the database as up to date (and seeds discount presets)
        if ($sample !== 'none') {
            $admin = (int) DB::value("SELECT id FROM users WHERE username = 'admin'");
            $prev = Auth::id();
            Auth::actAs($admin);     // sample stock-in documents are posted as the administrator
            try {
                Seeder::sample($sample);
            } finally {
                Auth::actAs($prev);
            }
        }
    }

    public static function isInstalled(): bool
    {
        try {
            return DB::tableExists('users') && (bool) DB::value('SELECT COUNT(*) FROM users');
        } catch (\Throwable $e) {
            return false;
        }
    }

    /** Local servers only: remember the database settings in config/config.php (Railway uses environment variables). */
    public static function writeConfig(array $db): void
    {
        $config = [
            'db' => $db,
            'app' => ['timezone' => config('app.timezone', 'Asia/Manila'), 'debug' => false, 'base_path' => config('app.base_path', ''), 'trust_proxy' => true],
        ];
        $php = "<?php\n// Generated by the installer. Edit to change database credentials.\nreturn " . var_export($config, true) . ";\n";
        if (file_put_contents(BASE_PATH . '/config/config.php', $php) === false) {
            throw new \RuntimeException('Could not write config/config.php — check folder permissions.');
        }
    }
}
